#!/usr/bin/env python3
"""Regenerate original Creator Essentials LUTs and their Kotlin matrix registry.

No downloaded grades or brand emulation. RGB lattice is red-fastest .cube order.
Matrices keep preview, thumbnails, photos and exported video on the same grade.
Run from any directory; existing preset IDs and categories remain unchanged.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# RGB rows with normalized offsets. Alpha is preserved in the Kotlin matrix.
GRADES = [
    ('creator_clean', 'Clean Studio', [[1.04, -.02, -.02, .005], [-.01, 1.03, -.02, .005], [-.01, -.02, 1.03, .005]]),
    ('creator_peach', 'Peach Portrait', [[1.025, .015, -.01, .012], [.01, .99, 0, .004], [.01, .01, .95, .008]]),
    ('creator_travel', 'Travel Pop', [[1.10, -.06, -.04, 0], [-.03, 1.08, -.05, .002], [-.03, -.04, 1.07, .008]]),
    ('creator_matte', 'Matte Story', [[.91, .02, .01, .035], [.01, .92, .01, .03], [.01, .01, .90, .04]]),
    ('creator_night', 'Night Editorial', [[1.01, -.02, -.01, -.008], [-.01, 1.00, .01, -.004], [0, .015, 1.025, .006]]),
    ('creator_mono', 'Soft Silver', [[.27508, .54004, .10488, .025]] * 3),
]


def main():
    assets = ROOT / 'app/src/main/assets/luts'
    lines = ['package com.apexstudio.app.data.filter', '',
             '/** Original Creator Essentials grades. Generated by scripts/generate-creator-luts.py. */',
             'internal object CreatorFilterPack {', '    fun matrix(id: String?): FloatArray? = when (id) {']
    for ident, name, rows in GRADES:
        values = [v for row in rows for v in (row[0], row[1], row[2], 0, row[3] * 255)] + [0, 0, 0, 1, 0]
        lines.append(f'        "{ident}" -> floatArrayOf(')
        for start in range(0, 20, 5):
            lines.append('            ' + ', '.join(f'{v:.6f}f' for v in values[start:start + 5]) + (',' if start < 15 else ''))
        lines.append('        )')
        output = [f'# Original ApexStudio Creator Essentials: {name}', f'TITLE "{name}"', 'LUT_3D_SIZE 17', 'DOMAIN_MIN 0 0 0', 'DOMAIN_MAX 1 1 1']
        for bi in range(17):
            for gi in range(17):
                for ri in range(17):
                    rgb = [ri / 16, gi / 16, bi / 16]
                    result = [max(0, min(1, sum(row[k] * rgb[k] for k in range(3)) + row[3])) for row in rows]
                    output.append(' '.join(f'{v:.6f}' for v in result))
        (assets / f'{ident}.cube').write_text('\n'.join(output) + '\n')
    lines.extend(['        else -> null', '    }', '}', ''])
    (ROOT / 'app/src/main/java/com/apexstudio/app/data/filter/CreatorFilterPack.kt').write_text('\n'.join(lines))
    path = assets / 'filter_manifest.json'
    manifest = json.loads(path.read_text())
    ids = {g[0] for g in GRADES}
    category = {'id': 'creator_essentials', 'name': 'Creator Essentials', 'filters': [g[0] for g in GRADES]}
    manifest['categories'] = [category] + [c for c in manifest['categories'] if c['id'] != category['id']]
    manifest['filters'] = [{'id': ident, 'name': name, 'category': category['name'], 'asset': f'luts/{ident}.cube'} for ident, name, _ in GRADES] + [f for f in manifest['filters'] if f['id'] not in ids]
    path.write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'Generated {len(GRADES)} original grades, matching preview matrices and 17^3 LUTs.')


if __name__ == '__main__':
    main()
